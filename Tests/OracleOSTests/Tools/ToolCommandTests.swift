}

// MARK: - ToolSchemas Tests

@Suite("ToolSchemas")
struct ToolSchemasTests {

    @Test("Schema for app launch has required 'app' argument")
    func schemaForAppLaunch() {
        let spec = ToolCommandSpec(family: .app, name: "launch")
        let schema = ToolSchemas.schema(for: spec)
        #expect(schema.requiredArguments.contains("app"))
        #expect(schema.description.isEmpty == false)
    }

    @Test("Schema for window focus has required 'app' argument")
    func schemaForWindowFocus() {
        let spec = ToolCommandSpec(family: .window, name: "focus")
        let schema = ToolSchemas.schema(for: spec)
        #expect(schema.requiredArguments.contains("app"))
    }

    @Test("Schema for semantic_click has required 'query' argument")
    func schemaForSemanticClick() {
        let spec = ToolCommandSpec(family: .click, name: "semantic_click")
        let schema = ToolSchemas.schema(for: spec)
        #expect(schema.requiredArguments.contains("query"))
    }

    @Test("Schema for semantic_type requires query and text")
    func schemaForSemanticType() {
        let spec = ToolCommandSpec(family: .type, name: "semantic_type")
        let schema = ToolSchemas.schema(for: spec)
        #expect(schema.requiredArguments.contains("query"))
        #expect(schema.requiredArguments.contains("text"))
    }

    @Test("Schema for snapshot has no required arguments")
    func schemaForSnapshot() {
        let spec = ToolCommandSpec(family: .capture, name: "snapshot")
        let schema = ToolSchemas.schema(for: spec)
        #expect(schema.requiredArguments.isEmpty)
    }

    @Test("Schema ID matches the spec ID")
    func schemaIDMatchesSpecID() {
        let spec = ToolCommandSpec(family: .app, name: "launch")
        let schema = ToolSchemas.schema(for: spec)
        #expect(schema.id == spec.id)
    }

    @Test("Unknown command returns default schema with no required arguments")
    func unknownCommandDefaultSchema() {
        let spec = ToolCommandSpec(family: .menu, name: "select")
        let schema = ToolSchemas.schema(for: spec)
        #expect(schema.id == spec.id)
    }

    @Test("ToolSchema is equatable by content")
    func toolSchemaEquality() {
        let a = ToolSchema(id: "x", description: "desc", requiredArguments: ["app"])
        let b = ToolSchema(id: "x", description: "desc", requiredArguments: ["app"])
        #expect(a == b)
    }
}
